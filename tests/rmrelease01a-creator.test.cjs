'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('creator.html'),js=read('creator-console.js'),css=read('creator-console.css'),auth=read('creator-auth.js');
test('RM-RELEASE-01A: public release controls are read-only and do not require new database tables',()=>{
 assert.match(html,/data-owner-nav="publications"/);
 assert.match(html,/data-owner-section="publications"/);
 assert.match(html,/id="ownerRefreshPublication"/);
 assert.match(js,/fetch\(new URL\('app-release\.json',location\.href\)/);
 assert.match(js,/fetch\(new URL\('reservation\/runtime\.json',location\.href\)/);
 assert.match(js,/credentials:'omit'/);
 assert.match(js,/portal\?\.channel!=='production'/);
 assert.match(js,/portal\?\.publicOrigin!==location\.origin/);
 assert.match(js,/Aucun contrôle de disponibilité serveur/);
 const start=js.indexOf(' async function loadPublication(){'),end=js.indexOf(' async function load(){',start);
 assert.ok(start>0&&end>start);
 const fn=js.slice(start,end);
 assert.doesNotMatch(fn,/\.rpc\s*\(|client\.from\s*\(|\.update\s*\(|\.insert\s*\(|\.delete\s*\(|\bPOST\b|service_role|auth\./);
 assert.doesNotMatch(html,/rm017_lifecycle_requests|rm017_establishment_profiles|rootdev|pilote DEV/i);
 assert.doesNotMatch(js,/rm017_lifecycle_requests|rm017_establishment_profiles|rootdev|pilote DEV/i);
});
