'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const M=require('../rm0173-pilot-model.js');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const valid={type:'independent',name:' Le Jardin (démo) ',siret:'00000000000000',email:'demo@example.test'};
test('RM-017.3.1: offline SIRET checksum and SIREN calculation are simulated, not official checks',()=>{
 assert.equal(M.validSiret(valid.siret),true);
 assert.equal(M.validSiret('123456789'),false);
 assert.equal(M.validSiret('12345678901234'),false);
 assert.equal(M.validSiret('0000000000000x'),false);
 assert.equal(M.validSiret('00000000000000 '),false);
 assert.deepEqual(M.validate(valid),{});
 assert.ok(M.validate({...valid,type:'untrusted'}).type);
 assert.ok(M.validate({...valid,name:'x'}).name);
 assert.ok(M.validate({...valid,siret:'1234'}).siret);
 assert.ok(M.validate({...valid,email:'no-email'}).email);
 assert.ok(M.validate({...valid,email:'a'.repeat(161)+'@example.test'}).email);
 assert.equal(M.maskSiret('00000000001234'),'••••••••••1234');
 assert.equal(M.maskEmail(valid.email),'de•••@example.test');
});
test('RM-017.3.1: user cannot create a restaurant without simulated email confirmation',()=>{
 const initial=M.empty();
 assert.equal(initial.account,'none');
 assert.equal(initial.restaurant,'none');
 assert.throws(()=>M.next(initial,'confirm-email'),/Aucun email fictif/);
 const pending=M.next(initial,'create',valid);
 assert.equal(pending.account,'pending_email');
 assert.equal(pending.restaurant,'none');
 assert.equal(pending.profile.siren,'000000000');
 assert.equal(pending.profile.fictional,true);
 assert.equal(pending.profile.name,'Le Jardin (démo)');
 assert.ok(Object.isFrozen(pending));
 assert.ok(Object.isFrozen(pending.events));
 assert.ok(Object.isFrozen(pending.profile));
 assert.equal(initial.account,'none','pure state transitions preserve original');
 assert.throws(()=>M.next(pending,'request-closure'),/Terminez/);
 assert.throws(()=>M.next(pending,'root-suspend'),/Terminez/);
 assert.throws(()=>M.next(pending,'create',valid),/Recommencez/);
 const active=M.next(pending,'confirm-email');
 assert.equal(active.account,'active');
 assert.equal(active.restaurant,'active');
 assert.deepEqual(active.events,['create','confirm-email']);
 assert.throws(()=>M.next(active,'confirm-email'),/Aucun email fictif/);
 assert.throws(()=>M.next(active,'create',valid),/Recommencez/);
});
test('RM-017.3.1: distinct account deletion and restaurant closure requests',()=>{
 const active=M.next(M.next(M.empty(),'create',valid),'confirm-email');
 const account=M.next(active,'request-account-delete');
 assert.equal(account.account,'deletion_requested');
 assert.equal(account.restaurant,'active','account request never erases the restaurant');
 assert.throws(()=>M.next(account,'request-account-delete'),/déjà enregistrée/);
 const closure=M.next(account,'request-closure');
 assert.equal(closure.account,'deletion_requested');
 assert.equal(closure.restaurant,'closure_requested');
 assert.throws(()=>M.next(closure,'request-closure'),/déjà demandée/);
 assert.equal(closure.profile.siret,'00000000000000');
});
test('RM-017.3.1: simulated Root suspension, restore, archive and erase are guarded',()=>{
 const active=M.next(M.next(M.empty(),'create',{...valid,type:'hotel'}),'confirm-email');
 assert.equal(active.profile.type,'hotel');
 assert.throws(()=>M.next(active,'root-archive'),/Suspendez/);
 assert.throws(()=>M.next(active,'root-erase'),/archivage/);
 const suspended=M.next(active,'root-suspend');
 assert.equal(suspended.restaurant,'suspended');
 assert.throws(()=>M.next(suspended,'root-suspend'),/Suspension impossible/);
 const restored=M.next(suspended,'root-restore');
 assert.equal(restored.restaurant,'active');
 const suspendedAgain=M.next(restored,'root-suspend');
 const archived=M.next(suspendedAgain,'root-archive');
 assert.equal(archived.restaurant,'archived');
 assert.throws(()=>M.next(archived,'root-restore'),/Seul un établissement suspendu/);
 const erased=M.next(archived,'root-erase');
 assert.equal(erased.account,'deleted');
 assert.equal(erased.restaurant,'erased');
 assert.equal(erased.profile,null);
 assert.equal(active.profile.name,'Le Jardin (démo)');
 assert.throws(()=>M.next(erased,'root-erase'),/Terminez/);
 assert.deepEqual(M.next(erased,'reset'),M.empty());
});
