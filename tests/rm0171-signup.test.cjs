'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const Model=require('../rm017-signup-model.js');
const valid={name:'  Le Jardin  ',city:'  Rouen ',email:'contact@example.test'};
test('RM-017.1: restaurant independent and hotel have distinct Lucide icon and configuration',()=>{
 assert.deepEqual(Object.keys(Model.types),['independent','hotel']);
 assert.equal(Model.types.independent.icon,'utensils');
 assert.equal(Model.types.hotel.icon,'hotel');
 assert.match(Model.types.hotel.features.join(' '),/chambre/i);
 assert.doesNotMatch(Model.types.independent.features.join(' '),/chambre/i);
 assert.equal(Model.validateType('other')!==null,true);
 assert.equal(Model.validateType('hotel'),null);
});
test('RM-017.1: validation of fictional professional draft',()=>{
 assert.deepEqual(Model.validateDetails(valid),{});
 assert.equal(Model.validateDetails({...valid,name:'X'}).name!==undefined,true);
 assert.equal(Model.validateDetails({...valid,city:''}).city!==undefined,true);
 assert.equal(Model.validateDetails({...valid,email:'bad address'}).email!==undefined,true);
 assert.equal(Model.validateDetails({...valid,email:'x'.repeat(161)+'@example.test'}).email!==undefined,true);
 assert.throws(()=>Model.preview('unsupported',valid),/incomplet/);
 assert.throws(()=>Model.preview('hotel',{...valid,email:''}),/incomplet/);
 const example=Model.preview('hotel',valid);
 assert.equal(example.label,"Restaurant d’hôtel");
 assert.equal(example.name,'Le Jardin');
 assert.equal(example.city,'Rouen');
 assert.equal(example.icon,'hotel');
 assert.equal(example.registered,false);
 assert.equal(example.fictional,true);
 assert.ok(Object.isFrozen(example));
});
