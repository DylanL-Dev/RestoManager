'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const cfg=JSON.parse(read('rm017-runtime.json')),app=read('rm017-register.js'),sql=read('supabase/migrations/20261122175200_rm01721_dev_email_pilot_allowlist.sql'),html=read('inscription.html');
test('pilot is entirely closed and scoped to the authorized Render DEV origin',()=>{
 assert.equal(cfg.schema,2);
 assert.equal(cfg.channel,'dev');
 assert.equal(cfg.enabled,false);
 assert.equal(cfg.pilotOnly,true);
 assert.equal(cfg.captchaRequired,true);
 assert.equal(cfg.confirmationEmailRequired,true);
 assert.equal(cfg.turnstileSiteKey,null);
 assert.equal(cfg.redirectOrigin,'https://restomanager-v3-supabase-integration.onrender.com');
 assert.match(app,/runtime\?\.schema!==2/);
 assert.match(app,/runtime\?\.enabled!==true/);
 assert.match(app,/runtime\?\.pilotOnly!==true/);
 assert.match(app,/runtime\?\.captchaRequired!==true/);
 assert.match(app,/runtime\?\.redirectOrigin!==location\.origin/);
 assert.doesNotMatch(html,/tnsrkargogckgtsxipwd|service_role|sb_secret_/);
});
test('Cloudflare Turnstile is required before any signup and token is reset after attempt',()=>{
 assert.match(html,/challenges\.cloudflare\.com/);
 assert.match(html,/id="registrationCaptcha"/);
 assert.match(app,/https:\/\/challenges\.cloudflare\.com\/turnstile\/v0\/api\.js\?render=explicit/);
 assert.match(app,/captchaToken:token/);
 assert.match(app,/!challengeToken/);
 assert.match(app,/resetCaptcha\(\)/);
 assert.match(app,/expired-callback/);
 assert.match(app,/error-callback/);
 assert.match(app,/await loadCaptcha\(key\)/);
 assert.match(html,/id="submitRegistration" disabled/);
});
test('verified return has a visible status even after reload; no mutable metadata is trusted for authorization',()=>{
 assert.match(html,/id="registrationVerification"/);
 assert.match(html,/id="verificationTitle"/);
 assert.match(html,/id="verificationText"/);
 assert.match(app,/auth\.getUser\(\)/);
 assert.match(app,/isConfirmationReturn/);
 assert.match(app,/safeUrl\(\)/);
 assert.match(app,/user\?\.email_confirmed_at/);
 assert.match(app,/\.rpc\('rm017_complete_signup_v1'/);
 assert.match(app,/emailRedirectTo:canonical/);
 assert.match(app,/data\?\.session/);
 assert.match(app,/auth\.signOut/);
 assert.doesNotMatch(sql.replace(/--[^\n]*/g,''),/raw_user_meta_data|app_metadata/);
});
