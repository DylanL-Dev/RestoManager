'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const tutorial=fs.readFileSync(path.join(root,'service-v3-tutorial.js'),'utf8');
